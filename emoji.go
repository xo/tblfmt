// emojiWidth returns the number of columns to add to the width that
// runewidth.StringWidth gives the text b.
//
// A base followed by U+FE0F is an emoji variation sequence. A terminal draws
// it as one emoji 2 columns wide. go-runewidth v0.0.31 counts it as 1 column
// when the base alone is narrow, such as U+2764 U+FE0F. This func adds the
// missing column for each such sequence. It asks go-runewidth for the width of
// the sequence first, so it adds nothing once go-runewidth counts it as 2.
//
// Note: a sequence that U+200D joins to another emoji is not counted.
// go-runewidth already counts the joined cluster as 2 columns.
//
// Note: this is a temporary workaround. Remove it when go-runewidth counts
// these sequences as 2 columns. See B38 in docs/BACKLOG.md.
func emojiWidth(b []byte) int {
	var n int
	for off := 0; ; {
		i := bytes.Index(b[off:], vs16)
		if i < 0 {
			return n
		}
		i += off
		off = i + len(vs16)
		r, size := utf8.DecodeLastRune(b[:i])
		prev, _ := utf8.DecodeLastRune(b[:i-size])
		next, _ := utf8.DecodeRune(b[off:])
		if i > 0 && prev != zwj && next != zwj && hasEmojiForm(r) &&
			runewidth.StringWidth(string(r)+string(vs16)) == 1 {
			n++
		}
	}
}

// zwj is U+200D, ZERO WIDTH JOINER.
const zwj = '\u200D'

// vs16 is U+FE0F, the selector for the emoji form, in UTF-8.
var vs16 = []byte("\uFE0F")

// hasEmojiForm reports whether r followed by U+FE0F is an emoji variation
// sequence.
func hasEmojiForm(r rune) bool {
	_, ok := slices.BinarySearchFunc(emojiForms, r, func(e [2]rune, r rune) int {
		switch {
		case r < e[0]:
			return 1
		case r > e[1]:
			return -1
		}
		return 0
	})
	return ok
}

